//! Exporter to generate web/spec.js directly from Rust source of truth.
//!
//! Run with: `cargo run --example export_spec`

use std::fs;
use std::path::Path;

use gpui::Rgba;
use gpui_m3e::{
    M3Palette, SliderMetrics, SpringParams, SwitchMetrics, dark_scheme, icon_segments,
    light_scheme,
};

fn rgba_to_hex(c: Rgba) -> String {
    format!(
        "#{:02x}{:02x}{:02x}",
        (c.r * 255.0).round() as u8,
        (c.g * 255.0).round() as u8,
        (c.b * 255.0).round() as u8,
    )
}

fn palette_to_js(p: &M3Palette) -> String {
    format!(
        r#"    surface: '{surface}',
    onSurface: '{on_surface}',
    onSurfaceVariant: '{on_surface_variant}',
    primary: '{primary}',
    onPrimary: '{on_primary}',
    primaryContainer: '{primary_container}',
    secondaryContainer: '{secondary_container}',
    onSecondaryContainer: '{on_secondary_container}',
    inverseSurface: '{inverse_surface}',
    inverseOnSurface: '{inverse_on_surface}',
    outline: '{outline}',
    outlineVariant: '{outline_variant}',
    surfaceContainerHighest: '{surface_container_highest}'"#,
        surface = rgba_to_hex(p.surface),
        on_surface = rgba_to_hex(p.on_surface),
        on_surface_variant = rgba_to_hex(p.on_surface_variant),
        primary = rgba_to_hex(p.primary),
        on_primary = rgba_to_hex(p.on_primary),
        primary_container = rgba_to_hex(p.primary_container),
        secondary_container = rgba_to_hex(p.secondary_container),
        on_secondary_container = rgba_to_hex(p.on_secondary_container),
        inverse_surface = rgba_to_hex(p.inverse_surface),
        inverse_on_surface = rgba_to_hex(p.inverse_on_surface),
        outline = rgba_to_hex(p.outline),
        outline_variant = rgba_to_hex(p.outline_variant),
        surface_container_highest = rgba_to_hex(p.surface_container_highest),
    )
}

fn spring_to_js(s: &SpringParams) -> String {
    format!(
        "{{ stiffness: {:.1}, damping: {:.1}, mass: {:.1} }}",
        s.stiffness, s.damping, s.mass
    )
}

fn seg_to_js(s: &gpui_m3e::IconSegment) -> String {
    format!(
        "{{ sX: {:.1}, sY: {:.1}, eX: {:.1}, eY: {:.1} }}",
        s.start_x, s.start_y, s.end_x, s.end_y
    )
}

fn main() {
    let dark = dark_scheme();
    let light = light_scheme();

    let slider_expressive = SpringParams::expressive();
    let slider_standard = SpringParams::standard();
    let switch_spring = SpringParams::standard();
    let press_spring = SpringParams {
        stiffness: 450.0,
        damping: 30.0,
        mass: 1.0,
    };
    let hover_spring = SpringParams {
        stiffness: 400.0,
        damping: 32.0,
        mass: 1.0,
    };

    let sm = SliderMetrics::default();
    let swm = SwitchMetrics::default();

    let (u_id1, u_id2) = icon_segments(false, false);
    let (c_id1, c_id2) = icon_segments(true, false);
    let (u_pr1, u_pr2) = icon_segments(false, true);
    let (c_pr1, c_pr2) = icon_segments(true, true);

    let js_content = format!(
        r#"// AUTOGENERATED FROM RUST (examples/export_spec.rs) - DO NOT EDIT BY HAND!
// To regenerate: cargo run --example export_spec

window.M3E_SPEC = {{
  defaultTheme: 'dark',
  palettes: {{
    dark: {{
{dark_pal}
    }},
    light: {{
{light_pal}
    }},
  }},
  springs: {{
    dt: 1.0 / 60.0,
    sliderExpressive: {slider_expressive},
    sliderStandard: {slider_standard},
    switch: {switch_spring},
    press: {press_spring},
    hover: {hover_spring},
  }},
  sliderMetrics: {{
    trackWidth: 480.0,
    trackHeight: {sm_track_h:.1},
    thumbWidthIdle: {sm_thumb_w:.1},
    thumbWidthPressed: 2.0,
    thumbHeightIdle: 40.0,
    thumbHeightHover: 44.0,
    thumbHeightPressed: 48.0,
    thumbGap: {sm_gap:.1},
    cutoutTotal: 12.0,
    stopDotSize: {sm_tick_size:.1},
    tooltipWidth: 56.0,
    tooltipHeight: 24.0,
  }},
  switchMetrics: {{
    trackWidth: {sw_track_w:.1},
    trackHeight: {sw_track_h:.1},
    trackRadius: 16.0,
    thumbWidthIdle: {sw_thumb_w_idle:.1},
    thumbWidthPressed: {sw_thumb_w_pressed:.1},
    thumbHeight: {sw_thumb_h:.1},
    travel: 20.0,
    iconSize: {sw_icon_size:.1},
    iconStrokeWidth: {sw_icon_stroke:.1},
  }},
  iconKeyframes: {{
    uncheckIdle: [{u_id1}, {u_id2}],
    checkIdle: [{c_id1}, {c_id2}],
    uncheckPress: [{u_pr1}, {u_pr2}],
    checkPress: [{c_pr1}, {c_pr2}],
  }},
  sliders: [
    {{ id: 'sl-0', title: 'Media Volume', min: 0.0, max: 100.0, steps: 0, value: 42.0, enabled: true, expressive: true }},
    {{ id: 'sl-1', title: 'Display Brightness', min: 0.0, max: 10.0, steps: 4, value: 6.0, enabled: true, expressive: true }},
    {{ id: 'sl-2', title: 'Balance', min: 0.0, max: 1.0, steps: 0, value: 0.5, enabled: false, expressive: false }},
  ],
  switches: [
    {{ id: 'sw-0', title: 'Airplane Mode', checked: true, enabled: true, showIcons: true }},
    {{ id: 'sw-1', title: 'Bluetooth', checked: false, enabled: true, showIcons: true }},
    {{ id: 'sw-2', title: 'Haptics', checked: true, enabled: true, showIcons: false }},
    {{ id: 'sw-3', title: 'Night Light', checked: true, enabled: false, showIcons: true }},
    {{ id: 'sw-4', title: 'Mobile Data', checked: false, enabled: false, showIcons: true }},
  ],
}};
"#,
        dark_pal = palette_to_js(&dark),
        light_pal = palette_to_js(&light),
        slider_expressive = spring_to_js(&slider_expressive),
        slider_standard = spring_to_js(&slider_standard),
        switch_spring = spring_to_js(&switch_spring),
        press_spring = spring_to_js(&press_spring),
        hover_spring = spring_to_js(&hover_spring),
        sm_track_h = sm.track_height,
        sm_thumb_w = sm.thumb_w,
        sm_gap = sm.thumb_gap,
        sm_tick_size = sm.tick_size,
        sw_track_w = swm.track_width,
        sw_track_h = swm.track_height,
        sw_thumb_w_idle = swm.thumb_width_idle,
        sw_thumb_w_pressed = swm.thumb_width_pressed,
        sw_thumb_h = swm.thumb_height,
        sw_icon_size = swm.icon_size,
        sw_icon_stroke = swm.icon_stroke_width,
        u_id1 = seg_to_js(&u_id1),
        u_id2 = seg_to_js(&u_id2),
        c_id1 = seg_to_js(&c_id1),
        c_id2 = seg_to_js(&c_id2),
        u_pr1 = seg_to_js(&u_pr1),
        u_pr2 = seg_to_js(&u_pr2),
        c_pr1 = seg_to_js(&c_pr1),
        c_pr2 = seg_to_js(&c_pr2),
    );

    let out_path = Path::new("web/spec.js");
    fs::write(out_path, js_content).expect("Failed to write web/spec.js");
    println!("Successfully exported M3E spec to {}", out_path.display());
}
